-- ── 3) purchase_orders.contact_person_id ─────────────────────────────────
alter table public.purchase_orders
  add column if not exists contact_person_id bigint;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'purchase_orders_contact_person_fk'
