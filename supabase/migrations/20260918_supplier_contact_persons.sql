-- 20260918_supplier_contact_persons.sql
-- Supplier contact PERSONS model (ek firm + 4 contact persons, ek person
-- ke 1+ mobiles, har deal ka apna person).
--
--  1. `supplier_contact_persons` — firm ke andar alag-alag contact person
--     (name, role/designation, notes, is_primary = main deal person).
--  2. `supplier_contact_phones`  — har person ke 1+ phone (label + is_primary
--     per phone). Purane `supplier_contacts` (flat phone rows) ko replace karta
--     hai; table ko DROP NAHI karte — legacy back-compat ke liye rehta hai.
--  3. `purchase_orders.contact_person_id`  — kaunsa PO kis person se deal thi.
--  4. `supplier_payments.contact_person_id` — payment kis person ko diya.
--
-- Follows docs/DATA_MIGRATION_NOTES.md + repo RLS pattern:
--   • bigint identity PK, FK cascade (owned-by) / on delete set null (PO/pay)
--   • RLS: `rlslock_*_staff` (is_frontend_staff() gate)
--   • grants anon/authenticated/service_role + sequence grants
--   • touch trigger (date_updated) persons table par
--   • idempotent: baar baar run safe
--
-- Apply: Supabase SQL Editor me run karo (ek baar). Verify:
--   select relname from pg_class where relnamespace='public'::regnamespace
--     and relname in ('supplier_contact_persons','supplier_contact_phones');
